"""
9_decision_layer.py

Implements Phase 2 of the risk-based trust decision framework using the
development out-of-fold risk scores generated by 8_risk_models_and_hybrid.py.
The test partitions are never opened.

Each model arrangement provides a risk score r = P(malicious), based on the
binary target (0 = benign, 1 = malicious). This script converts risk scores
into three trust levels and corresponding access decisions using two
thresholds:

    - Trusted:     r < tau1       -> Allow
    - Suspicious:  tau1 <= r < tau2 -> Restrict
    - Untrusted:   r >= tau2      -> Reject

Trust levels are derived from model risk scores and cost-based thresholds.
Original attack types and detailed labels are used only to analyse where
flows fall within the resulting trust levels; they are not used to assign
trust levels or select thresholds.

The decision framework uses a three-way cost model with:
    - C: cost ratio of falsely trusting malicious traffic to rejecting
      benign traffic.
    - b: cost of restricting benign traffic relative to rejecting it.
    - rho: proportion of false-trust harm remaining when malicious traffic
      is restricted rather than allowed.

Bayes-optimal thresholds are calculated under the assumption that risk
scores are calibrated probabilities. Because class weighting and differences
in class distributions can affect calibration, the thresholds used for
decisions are selected empirically by minimising mean cost over the
development out-of-fold scores.

Threshold selection evaluates pairs tau1 <= tau2 on a grid from 0.00 to
1.00, including a 'never' threshold. Ties are resolved by the first minimum,
with tau2 as the outer search dimension and tau1 as the inner dimension.
The primary cost parameters are b = rho = 1/3, and the cost ratio C is
evaluated at 1, 2, 5, 10, and 20.

The analysis includes:
    - Trade-off curves showing false-trust and over-restriction rates.
    - Empirically selected thresholds and corresponding Bayes thresholds.
    - Cross-validated threshold decisions, where thresholds are selected
      using the other folds and applied to the held-out fold.
    - A reference decision rule without an intermediate trust level:
      r >= 0.5 -> Reject; otherwise -> Allow.
    - Decision metrics, including false-trust rates, restriction and
      rejection rates, trust-level shares, malicious shares within each
      trust level, and mean decision costs.
    - Distributions of original attack types or detailed labels across the
      Trusted, Suspicious, and Untrusted levels.
    - Sensitivity analysis over different values of b, rho, and C.

For RT-IoT2022, all development rows are used for threshold selection and
evaluation. For IoT-23, unseen-capture rows are the primary selection set,
with all rows used as a secondary selection set. IoT-23 results are reported
for unseen-capture rows, Capture-35-1 rows, and all rows.

Usage:
    python src/9_decision_layer.py rt_iot2022
    python src/9_decision_layer.py iot23
    python src/9_decision_layer.py
"""

import os
import sys
import json

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
IN_DIR = os.path.join(PROJECT_ROOT, "results", "08_risk_models")
OUT_DIR = os.path.join(PROJECT_ROOT, "results", "09_decision_layer")
FIG_DIR = os.path.join(OUT_DIR, "figures")
os.makedirs(FIG_DIR, exist_ok=True)

LEVELS = ["Trusted", "Suspicious", "Untrusted"]
ACTIONS = ["Allow", "Restrict", "Reject"]
ARRANGEMENTS = ["hybrid_xgb_rf", "xgboost_alone", "random_forest_alone", "hybrid_rf_xgb"]
FINE_LABEL = {"iot23": "detailed_label", "rt_iot2022": "attack_type"}
COST_RATIOS = [1, 2, 5, 10, 20]
B_PRIMARY = 1 / 3          # cost of restricting a benign flow (reject = 1)
RHO_PRIMARY = 1 / 3        # share of false-trust harm left when a malicious flow is restricted
SENS_VALUES = [0.1, 0.2, 1 / 3, 0.5]
GRID = np.round(np.linspace(0.0, 1.0, 101), 2)
G = len(GRID)
NEVER = G                  # threshold index G = "above 1": never reached


def tau_label(a):
    return float(GRID[a]) if a < G else float("inf")

# cost model
def cost_matrix(C, b, rho):
    """rows: true benign (0), malicious (1); columns: Allow, Restrict, Reject."""
    return np.array([[0.0, b, 1.0], [C, rho * C, 0.0]])


def bayes_thresholds(C, b, rho):
    t1 = b / (b + (1 - rho) * C)
    t2 = (1 - b) / ((1 - b) + rho * C)
    if t1 >= t2:                                    # b + rho >= 1: no Suspicious band
        t = 1 / (1 + C)                             # Allow / Reject boundary
        return t, t, False
    return t1, t2, True

# exact outcome tables for every threshold pair
def grid_index(r):
    """k such that GRID[a] <= r  <=>  a <= k."""
    return np.clip(np.searchsorted(GRID, r, side="right") - 1, 0, G - 1)


def outcome_tables(y, r):
    """counts[c, action, a1, a2] for tau1 = GRID[a1], tau2 = GRID[a2]
    (index G = never); only a1 <= a2 is meaningful."""
    k = grid_index(r)
    H = np.zeros((2, G + 1))
    for c in (0, 1):
        H[c, :G] = np.bincount(k[y == c], minlength=G)
    below = np.concatenate([np.zeros((2, 1)), np.cumsum(H, axis=1)], axis=1)[:, :G + 1]  # rows with k < a
    total = H.sum(axis=1)
    allow = np.broadcast_to(below[:, :, None], (2, G + 1, G + 1))
    rej = np.broadcast_to((total[:, None] - below)[:, None, :], (2, G + 1, G + 1))
    res = np.broadcast_to(below[:, None, :], (2, G + 1, G + 1)) - allow
    counts = np.stack([allow, res, rej], axis=1).copy()
    valid = np.triu(np.ones((G + 1, G + 1), dtype=bool))
    return counts, total, valid


def mean_cost_table(counts, total, C, b, rho):
    return np.einsum("ca,caij->ij", cost_matrix(C, b, rho), counts) / total.sum()


def choose(counts, total, valid, C, b, rho):
    mc = np.where(valid, mean_cost_table(counts, total, C, b, rho), np.inf)
    idx = int(np.argmin(mc.T))            # row-major over (a2, a1): tau2 outer, tau1 inner
    a2, a1 = divmod(idx, G + 1)
    return a1, a2, float(mc[a1, a2])


def frontier(counts, total):
    """Trade-off over tau1 (tau2 = never): false trust vs over-restriction."""
    a1 = np.arange(G + 1)
    ftr = counts[1, 0, a1, NEVER] / total[1]
    orr = 1 - counts[0, 0, a1, NEVER] / total[0]
    return pd.DataFrame({"tau1": [tau_label(a) for a in a1],
                         "false_trust_rate": ftr, "over_restriction_rate": orr})

# metrics for a set of decisions
def decide(r, t1, t2):
    return np.where(r >= t2, 2, np.where(r >= t1, 1, 0))


def decision_metrics(y, action, b=B_PRIMARY, rho=RHO_PRIMARY):
    out = {"n": int(len(y)), "n_benign": int((y == 0).sum()), "n_malicious": int((y == 1).sum())}

    def rate(true_c, acts):
        m = y == true_c
        return float(np.isin(action[m], acts).mean()) if m.any() else float("nan")
    out["false_trust_rate_allow_given_malicious"] = rate(1, [0])
    out["malicious_restricted_rate"] = rate(1, [1])
    out["malicious_rejected_rate"] = rate(1, [2])
    out["over_restriction_rate_given_benign"] = rate(0, [1, 2])
    out["benign_restricted_rate"] = rate(0, [1])
    out["benign_rejected_rate"] = rate(0, [2])
    for k, lvl in enumerate(LEVELS):
        m = action == k
        out[f"share_{lvl}"] = float(m.mean())
        out[f"malicious_share_within_{lvl}"] = float(y[m].mean()) if m.any() else float("nan")
    for C in COST_RATIOS:
        cm = cost_matrix(C, b, rho)
        out[f"mean_cost_C{C}"] = float(cm[y, action].mean())
    out["decision_matrix_true_BM_x_action_ARJ"] = [[int(((y == c) & (action == a)).sum()) for a in range(3)]
                                                  for c in (0, 1)]
    return out


def landing_table(fine, y, action):
    """Share of each original attack type / detailed label in each trust level."""
    df = pd.DataFrame({"fine_label": fine, "true_class": y, "level": np.array(LEVELS)[action]})
    t = pd.crosstab(df["fine_label"], df["level"], normalize="index").reindex(columns=LEVELS, fill_value=0)
    t["n"] = df["fine_label"].value_counts()
    t["true_class"] = df.groupby("fine_label")["true_class"].first()
    return t.round(4)


# ----------------------------------------------------------------------

def load(ds):
    df = pd.read_csv(os.path.join(IN_DIR, f"{ds}_oof_probabilities.csv"), low_memory=False)
    y = df["true_class"].to_numpy(dtype=np.int64)
    fold = df["fold"].to_numpy(dtype=np.int64)
    fine = df[FINE_LABEL[ds]].astype(str).to_numpy()
    groups = {"all": np.ones(len(df), dtype=bool)}
    if ds == "iot23":
        groups["unseen_capture_rows"] = (df["scenario_group"] == "whole_scenario").to_numpy()
        groups["capture35_rows"] = ~groups["unseen_capture_rows"]
        rowsets = {"unseen_capture_rows": groups["unseen_capture_rows"], "all": groups["all"]}
    else:
        rowsets = {"all": groups["all"]}
    risks = {arr: np.clip(df[f"{arr}_risk"].to_numpy(dtype=np.float64), 0, 1) for arr in ARRANGEMENTS}
    return y, fold, fine, groups, rowsets, risks


def cv_actions(y, r, fold, rs, C, b, rho):
    """Thresholds chosen on the other folds, applied to each held-out fold."""
    action = np.empty(len(y), dtype=np.int64)
    thr = {}
    for f in np.unique(fold):
        m = rs & (fold != f)
        c_f, tot_f, val = outcome_tables(y[m], r[m])
        a1, a2, _ = choose(c_f, tot_f, val, C, b, rho)
        thr[int(f)] = [tau_label(a1), tau_label(a2)]
        held = fold == f
        action[held] = decide(r[held], tau_label(a1), tau_label(a2))
    return action, thr


def run(ds):
    print("=" * 70 + f"\nDECISION LAYER: {ds} (development out-of-fold data only)\n" + "=" * 70)
    y, fold, fine, groups, rowsets, risks = load(ds)
    primary_rows = "unseen_capture_rows" if ds == "iot23" else "all"
    metric_rows, thresholds, fronts, landing, sens = [], [], [], [], []

    for arr in ARRANGEMENTS:
        r = risks[arr]
        ref = (r >= 0.5).astype(np.int64) * 2           # Allow / Reject only
        for g, gm in groups.items():
            metric_rows.append({"arrangement": arr, "decision_rule": "no_trust_layer_r_ge_0.5_reject",
                                "threshold_rows": "-", "cost_ratio": None, "b": None, "rho": None,
                                "group": g, **decision_metrics(y[gm], ref[gm])})
        for rs_name, rs in rowsets.items():
            counts, total, valid = outcome_tables(y[rs], r[rs])
            fr = frontier(counts, total)
            fr.insert(0, "threshold_rows", rs_name)
            fr.insert(0, "arrangement", arr)
            fronts.append(fr)
            for C in COST_RATIOS:
                a1, a2, mc = choose(counts, total, valid, C, B_PRIMARY, RHO_PRIMARY)
                bt1, bt2, band = bayes_thresholds(C, B_PRIMARY, RHO_PRIMARY)
                action, cv_thr = cv_actions(y, r, fold, rs, C, B_PRIMARY, RHO_PRIMARY)
                thresholds.append({"arrangement": arr, "threshold_rows": rs_name, "cost_ratio": C,
                                   "b": B_PRIMARY, "rho": RHO_PRIMARY,
                                   "tau1_restrict": tau_label(a1), "tau2_reject": tau_label(a2),
                                   "bayes_tau1": bt1, "bayes_tau2": bt2,
                                   "suspicious_band_width": tau_label(a2) - tau_label(a1)
                                   if a2 < G else 1.0 - tau_label(a1),
                                   "selection_mean_cost": mc, "chosen_on": "all development folds",
                                   "cv_thresholds_by_held_out_fold": cv_thr})
                for g, gm in groups.items():
                    metric_rows.append({"arrangement": arr, "decision_rule": "cost_minimising_thresholds",
                                        "threshold_rows": rs_name, "cost_ratio": C, "b": B_PRIMARY,
                                        "rho": RHO_PRIMARY, "group": g,
                                        "evaluation": "cross-validated thresholds",
                                        **decision_metrics(y[gm], action[gm])})
                if rs_name == primary_rows:
                    dec = groups[primary_rows]
                    t = landing_table(fine[dec], y[dec], action[dec])
                    t.insert(0, "cost_ratio", C)
                    t.insert(0, "arrangement", arr)
                    landing.append(t.reset_index())
        # sensitivity analysis on the primary selection rows (cross-validated thresholds)
        rs = rowsets[primary_rows]
        counts, total, valid = outcome_tables(y[rs], r[rs])
        dec = groups[primary_rows]
        for b in SENS_VALUES:
            for rho in SENS_VALUES:
                for C in COST_RATIOS:
                    a1, a2, mc = choose(counts, total, valid, C, b, rho)
                    bt1, bt2, band = bayes_thresholds(C, b, rho)
                    action, _ = cv_actions(y, r, fold, rs, C, b, rho)
                    dm = decision_metrics(y[dec], action[dec], b, rho)
                    sens.append({"arrangement": arr, "b": round(b, 4), "rho": round(rho, 4),
                                 "b_plus_rho": round(b + rho, 4), "cost_ratio": C,
                                 "bayes_band_exists": band, "bayes_tau1": bt1, "bayes_tau2": bt2,
                                 "tau1_restrict": tau_label(a1), "tau2_reject": tau_label(a2),
                                 "selection_mean_cost": mc,
                                 **{k: v for k, v in dm.items() if not k.startswith(("decision_matrix", "mean_cost_C"))},
                                 "mean_cost": float(cost_matrix(C, b, rho)[y[dec], action[dec]].mean())})

    met = pd.DataFrame(metric_rows)
    thr = pd.DataFrame(thresholds)
    front = pd.concat(fronts, ignore_index=True)
    land = pd.concat(landing, ignore_index=True)
    sen = pd.DataFrame(sens)
    met.drop(columns=["decision_matrix_true_BM_x_action_ARJ"]).to_csv(
        os.path.join(OUT_DIR, f"{ds}_decision_metrics.csv"), index=False)
    with open(os.path.join(OUT_DIR, f"{ds}_decision_matrices.json"), "w") as f:
        json.dump([{k: r[k] for k in ("arrangement", "decision_rule", "threshold_rows", "cost_ratio",
                                       "group", "decision_matrix_true_BM_x_action_ARJ")}
                   for r in metric_rows], f, indent=1)
    thr.to_csv(os.path.join(OUT_DIR, f"{ds}_thresholds.csv"), index=False)
    front.to_csv(os.path.join(OUT_DIR, f"{ds}_tradeoff_frontier.csv"), index=False)
    land.to_csv(os.path.join(OUT_DIR, f"{ds}_trust_level_by_attack_type.csv"), index=False)
    sen.to_csv(os.path.join(OUT_DIR, f"{ds}_sensitivity.csv"), index=False)
    with open(os.path.join(OUT_DIR, f"{ds}_cost_model.json"), "w") as f:
        json.dump({"cost_matrix_rows_benign_malicious_cols_allow_restrict_reject":
                   "[[0, b, 1], [C, rho*C, 0]]", "b_primary": B_PRIMARY, "rho_primary": RHO_PRIMARY,
                   "cost_ratios": COST_RATIOS, "sensitivity_values_b_rho": SENS_VALUES,
                   "bayes_tau1": "b / (b + (1 - rho) * C)", "bayes_tau2": "(1 - b) / ((1 - b) + rho * C)",
                   "band_exists_iff": "b + rho < 1",
                   "bayes_thresholds_primary": {str(C): bayes_thresholds(C, B_PRIMARY, RHO_PRIMARY)[:2]
                                                for C in COST_RATIOS}}, f, indent=2)

    # figure 1: trade-off curves (over tau1) on the primary selection rows
    fig, ax = plt.subplots(figsize=(7.5, 5.5))
    for arr in ARRANGEMENTS:
        fr = front[(front["arrangement"] == arr) & (front["threshold_rows"] == primary_rows)]
        ax.plot(fr["false_trust_rate"], fr["over_restriction_rate"], label=arr)
    ax.set_xlabel("False-trust rate  P(Allow | malicious)")
    ax.set_ylabel("Over-restriction rate  P(Restrict or Reject | benign)")
    ax.set_title(f"{ds}: trade-off over tau1 on {primary_rows} (development, out-of-fold)", fontsize=9)
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG_DIR, f"{ds}_tradeoff_curves.png"), dpi=200)
    plt.close(fig)

    # figure 2: risk-score distribution of the primary hybrid with the C = 1 thresholds
    r = risks["hybrid_xgb_rf"][groups[primary_rows]]
    yy = y[groups[primary_rows]]
    t = thr[(thr["arrangement"] == "hybrid_xgb_rf") & (thr["threshold_rows"] == primary_rows)
            & (thr["cost_ratio"] == 1)].iloc[0]
    fig, ax = plt.subplots(figsize=(7.5, 4.5))
    bins = np.linspace(0, 1, 51)
    ax.hist(r[yy == 0], bins=bins, alpha=0.6, label="benign", density=True)
    ax.hist(r[yy == 1], bins=bins, alpha=0.6, label="malicious", density=True)
    for v, ls in ((t["tau1_restrict"], "--"), (t["tau2_reject"], ":")):
        if np.isfinite(v):
            ax.axvline(v, color="k", ls=ls)
    ax.set_xlabel("Risk score r = P(malicious)")
    ax.set_ylabel("Density")
    ax.set_title(f"{ds}: hybrid risk scores; dashed = tau1, dotted = tau2 (C = 1)", fontsize=9)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG_DIR, f"{ds}_risk_distribution_hybrid.png"), dpi=200)
    plt.close(fig)

    # console summary
    show = ["arrangement", "decision_rule", "cost_ratio", "false_trust_rate_allow_given_malicious",
            "over_restriction_rate_given_benign", "share_Suspicious", "malicious_share_within_Suspicious",
            "mean_cost_C1"]
    view = met[(met["group"] == primary_rows) & ((met["threshold_rows"] == primary_rows) |
                                                 (met["decision_rule"] != "cost_minimising_thresholds"))]
    print(f"\nDecisions on {primary_rows} (cross-validated thresholds chosen on {primary_rows}; "
          f"b = rho = {B_PRIMARY:.3f}):")
    print(view[show].round(4).to_string(index=False))
    print("\nThresholds (chosen on all development folds) vs Bayes thresholds:")
    print(thr[thr["threshold_rows"] == primary_rows][["arrangement", "cost_ratio", "tau1_restrict", "tau2_reject",
                                                       "bayes_tau1", "bayes_tau2", "selection_mean_cost"]]
          .round(4).to_string(index=False))
    print("\nWhere each attack type lands (hybrid, C = 1, cross-validated thresholds):")
    print(land[(land["arrangement"] == "hybrid_xgb_rf") & (land["cost_ratio"] == 1)]
          .drop(columns=["arrangement", "cost_ratio"]).to_string(index=False))
    s1 = sen[sen["arrangement"] == "hybrid_xgb_rf"]
    print("\nSensitivity (hybrid): share of flows in the Suspicious band, by (b, rho) and C:")
    print(s1.pivot_table(index=["b", "rho"], columns="cost_ratio", values="share_Suspicious").round(3).to_string())
    print("\nSensitivity (hybrid): false-trust rate, by (b, rho) and C:")
    print(s1.pivot_table(index=["b", "rho"], columns="cost_ratio",
                         values="false_trust_rate_allow_given_malicious").round(3).to_string())
    print(f"\nSaved: results/09_decision_layer/{ds}_*\n")


if __name__ == "__main__":
    for ds in sys.argv[1:] or ["rt_iot2022", "iot23"]:
        run(ds)
    print("Done.")